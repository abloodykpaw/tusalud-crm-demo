export function loadData(): AppData {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw) as AppData;
      if (!parsed.payments) parsed.payments = [];
      if (!parsed.historyEvents) parsed.historyEvents = [];
      if (typeof parsed.forcePaymentWindow !== "boolean") parsed.forcePaymentWindow = false;
      if (!parsed.currentWeekStart) parsed.currentWeekStart = WEEK_START;
      if (typeof parsed.weekNumber !== "number") parsed.weekNumber = WEEK_NUMBER;
      return { ...parsed, ...rollWeekForward(parsed) };
    }
  } catch {
    /* ignore */
  }
  const seed = createSeedData();
  saveData(seed);
  return seed;
}

export function saveData(data: AppData) {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
}

export function resetData() {
  localStorage.removeItem(STORAGE_KEY);
  return createSeedData();
}

